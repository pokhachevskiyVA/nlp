def domain(c):
    s=str(c)
    if s.startswith('таргет_') or s in ('Unnamed: 0','Unnamed: 1','NewVar','Кластер','источник_RR','_есть_RR_газ',
                                        'результативность_PC1','кластер','предстарт','старт','восстановление','Wmax','ЧССпокой'):
        return 'служебное'
    if 'км' in s.lower() or s.lower().startswith('точка'): return 'результат'
    # RR восстановление
    if re.match(r'^\d+В_',s) or s.startswith(('В_a','В_b','В_перегиб','Возв','В1_','В2_','В3_','ВN','Внак_','В_всего')) \
       or s.startswith('ЧСС_') and 'восст' in s or s.startswith('HRR'): return 'RR_восстановление'
    if s.startswith('газ_восст'): return 'газ_восстановление'
    # RR нагрузка
    if re.match(r'^(ПС|СТ|\d+Н)_',s) or s.startswith(('Н_a','Н_b','Н_перегиб','Н_R2','Н_a2','Н_доля','Мих','М15_','М25_','М35_',
        'разброс','м1_','м2_','м3_','м12_','м23_','м13_','Н1_','Н2_','Н3_','НN','Ннак_','Н_всего','ЧСС_посл','мин_нагрузки')): return 'RR_нагрузка'
    if s.startswith('газ_т'): return 'газ_точки'
    if s.startswith('газ_'): return 'газ_точки'
    if s.startswith('dW_'): return 'пульсовая_цена'
    if any(k in s for k in STAB_KEYS): return 'стабилометрия'
    if any(k in s for k in HRV_REST): return 'ВСР_покой'
    if any(s.startswith(k) or k in s for k in GASK): return 'газ_сводные'
    if any(k in s for k in PSY): return 'психология'
    if any(s.startswith(k) for k in ANAT): return 'анатомия'
    if any(k in s for k in STAB_KEYS): return 'стабилометрия'
    return 'прочее'
