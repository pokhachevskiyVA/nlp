_UNIT_TAIL = re.compile(r"[,;].*$|\(.*$")


def _norm(name):
    s = str(name)
    s = re.sub(r"__\d+$", "", s)          # убрать суффикс дубликата
    s = s.replace("\n", " ").strip()
    return s


def describe(col):
    """Возвращает (категория, описание) для столбца простыми словами."""
    try:
        from глоссарий_газ import описать
        _г = описать(col)
        if _г:
            return _г
    except Exception:
        pass
    n = _norm(col)
    low = n.lower()
    for pat, cat, desc in RULES:
        if re.search(pat, low):
            return cat, desc
