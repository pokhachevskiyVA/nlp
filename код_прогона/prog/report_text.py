_THEMES = {"pleiad": PLEIAD, "regression": REGRESSION, "ml": ML}


def write_methodology(wb, kind):
    """Создаёт лист «Как читать отчёт» с пояснениями метода."""
    name = "Как читать отчёт"
    if name in wb.sheetnames:
        return wb[name]
    ws = wb.create_sheet(name, 0)          # первым листом
    ws.column_dimensions["A"].width = 34
    ws.column_dimensions["B"].width = 105
    t = ws.cell(1, 1, "КАК ЧИТАТЬ ЭТОТ ОТЧЁТ")
    t.font = Font(bold=True, size=14, color="FFFFFFFF"); t.fill = _TITLE_FILL
    ws.cell(1, 2, "").fill = _TITLE_FILL
    ws.cell(2, 1, "Пояснение")
    intro = ws.cell(2, 2, INTRO); intro.alignment = Alignment(wrap_text=True, vertical="top")
    ws.cell(2, 1).font = Font(italic=True)
    r = 4
    for head, body in _THEMES.get(kind, COMMON):
        h = ws.cell(r, 1, head); h.font = Font(bold=True)
        h.alignment = Alignment(wrap_text=True, vertical="top")
        b = ws.cell(r, 2, body); b.alignment = Alignment(wrap_text=True, vertical="top")
        ws.row_dimensions[r].height = max(30, 14 * (len(body) // 95 + 1))
        r += 1
    ws.sheet_view.showGridLines = False
    return ws
