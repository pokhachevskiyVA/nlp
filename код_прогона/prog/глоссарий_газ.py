_Ннак_N = re.compile(r'^Ннак_N(\d)$')
_Ннак_Σ = re.compile(r'^Ннак_Σ(\d+)$')
_Н_пер  = re.compile(r'^(\d)Н_(.+)$')
_В_пер  = re.compile(r'^(\d)В_(.+)$')

def описать(col):
    s = str(col).strip()
    if s in ПРОЧЕЕ:
        return ПРОЧЕЕ[s]
    m = _Ннак_N.match(s)
    if m:
        i = int(m.group(1))
        фаза = 'нагрузка по ДОО' if i <= 3 else 'разгон +30 Вт/мин'
        return ('Кардио (счёт ударов)',
                f'накопленное число ударов к концу {i}-й минуты нагрузки ({фаза})')
    m = _Ннак_Σ.match(s)
    if m:
        k = m.group(1)
        return ('Кардио (счёт ударов)',
                f'время накопления первых {k} кардиоинтервалов, мс — чем меньше, тем выше пульс в начале нагрузки')
    m = _Н_пер.match(s)
    if m:
        i, п = int(m.group(1)), m.group(2)
        фаза = 'нагрузка по ДОО' if i <= 3 else 'разгон +30 Вт/мин'
        return ('ВСР на нагрузке', f'{п} за {i}-ю минуту нагрузки ({фаза})')
    m = _В_пер.match(s)
    if m:
        return ('ВСР на восстановлении', f'{m.group(2)} за {m.group(1)}-ю минуту восстановления')
    if not s.startswith('газ_'):
        return None
    ост = s[4:]
    for ключ, момент in МОМЕНТ:
        if ост.startswith(ключ + '_'):
            п = ост[len(ключ) + 1:]
            кат, оп = ПОКАЗАТЕЛЬ.get(п, ('Газообмен', п))
            return (кат, f'{оп[0].upper()}{оп[1:]}. Момент: {момент}.')
        if ост == ключ:
            return ('Газообмен', f'Момент: {момент}.')
    return None
