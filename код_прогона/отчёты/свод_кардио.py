    T=pd.to_numeric(d['мин_нагрузки'],errors='coerce'); Δ=30*(T.where(T>3)-3)
    ряд=[]
    for i in (1,2,3,4,5):
        c=f'{i}Н_ЧСС'
        if c not in d.columns: ряд.append((i,np.nan,np.nan,np.nan,0)); continue
        v=pd.to_numeric(d[c],errors='coerce'); m=v.notna()&Δ.notna()
        r,p=st.spearmanr(v[m],Δ[m])
        ряд.append((i,v[m].median(),r,p,int(m.sum())))
    ранние[л]=ряд

